function translateTemplate(value: string): string {
  let match: RegExpMatchArray | null;
  if ((match = value.match(/^(\d+) metrics$/))) return `${match[1]} 项指标`;
  if ((match = value.match(/^Refresh (.+)$/))) return `刷新 ${match[1]}`;
  if ((match = value.match(/^Close (.+)$/))) return `关闭 ${match[1]}`;
  if ((match = value.match(/^Hide (.+)$/))) return `隐藏 ${match[1]}`;
  if ((match = value.match(/^Show (.+)$/))) return `显示 ${match[1]}`;
  if ((match = value.match(/^Limit (.+)$/))) return `重置 ${match[1]}`;
  if ((match = value.match(/^at (.+)$/))) return match[1];
  if ((match = value.match(/^(.+): (.+)$/)))
    return `${translateChinese(match[1])}：${translateChinese(match[2])}`;
  if ((match = value.match(/^Resets in (.+)$/))) return `${match[1]} 后重置`;
  if ((match = value.match(/^Resets (.+)$/))) return `重置时间：${match[1]}`;
  if ((match = value.match(/^Reset in (.+)$/))) return `${match[1]} 后重置`;
  if ((match = value.match(/^Last updated (.+)$/))) return `上次更新：${match[1]}`;
  if ((match = value.match(/^Next update (.+)$/))) return `下次更新：${match[1]}`;
  if ((match = value.match(/^Updated (.+)$/))) return `更新于 ${match[1]}`;
  if ((match = value.match(/^~(\d+)% left at reset$/))) return `重置时预计剩余约 ${match[1]}%`;
  if ((match = value.match(/^~(\d+)% used at reset$/))) return `重置时预计已用约 ${match[1]}%`;
  if ((match = value.match(/^(\d+)% (used|left)$/)))
    return `${match[2] === 'used' ? '已用' : '剩余'} ${match[1]}%`;
  if ((match = value.match(/^(\d+) available$/))) return `可用 ${match[1]} 次`;
  if ((match = value.match(/^(.+) model usage$/))) return `${translateChinese(match[1])}模型用量`;
  if ((match = value.match(/^Downloaded (.+)$/))) return `已下载 ${match[1]}`;
  if ((match = value.match(/^Version (.+)$/))) return `版本 ${match[1]}`;
  return value;
}

export function translateChinese(value: string): string {
  const normalized = value.trim();
  if (!normalized) return value;
  const translated = translations[normalized] ?? translateTemplate(normalized);
  return translated === normalized ? value : value.replace(normalized, translated);
}

const translatedAttributes = ['aria-label', 'title', 'placeholder', 'data-tooltip'] as const;

function localizeNode(node: Node): void {
  if (node.nodeType === Node.TEXT_NODE) {
    const parent = node.parentElement;
    if (!parent || ['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(parent.tagName)) return;
    const current = node.textContent ?? '';
    const translated = translateChinese(current);
    if (translated !== current) node.textContent = translated;
    return;
  }
  if (!(node instanceof Element)) return;
  for (const attribute of translatedAttributes) {
    const current = node.getAttribute(attribute);
    if (!current) continue;
    const translated = translateChinese(current);
    if (translated !== current) node.setAttribute(attribute, translated);
  }
  for (const child of node.childNodes) localizeNode(child);
}

export function installSimplifiedChineseUi(): () => void {
  document.documentElement.lang = 'zh-CN';
  document.title = 'OpenQuota 简体中文版';
  localizeNode(document.body);
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') localizeNode(record.target);
      for (const node of record.addedNodes) localizeNode(node);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  return () => observer.disconnect();
}

export function localizeCurrentDocument(): void {
  localizeNode(document.body);
}
